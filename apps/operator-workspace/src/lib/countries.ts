const KNOWN = new Set<string>(COUNTRY_CODES);

export function isCountryCode(value: string): boolean {
  return KNOWN.has(value);
}

/**
 * A country in the reader's language. A well-formed code the runtime has no
 * name for is answered as itself (`fallback: "code"`), so a row never reads
 * blank.
 */
export function countryName(code: string, locale: string): string {
  return (
    new Intl.DisplayNames([locale], { type: "region", fallback: "code" }).of(
      code,
    ) ?? code
  );
}

/**
 * Names people still type that the locale data no longer carries, by code:
 * "Turkey" for a country CLDR now calls Türkiye is the one a Turkish dormitory
 * hits all day.
 */
const ALSO_KNOWN_AS: Readonly<Record<string, readonly string[]>> = {
  AE: ["UAE", "Emirates"],
  CI: ["Ivory Coast"],
  CV: ["Cape Verde"],
  CZ: ["Czech Republic"],
  GB: ["UK", "Britain", "England", "Scotland", "Wales"],
  MK: ["Macedonia"],
  MM: ["Burma"],
  RU: ["Russian Federation"],
  SZ: ["Swaziland"],
  TL: ["East Timor"],
  TR: ["Turkey", "Turkiye"],
  US: ["USA", "America", "United States of America"],
};

/** Accents and Turkish dots removed, so "turkiye" finds "Türkiye" and "cin" finds "Çin". */
function plain(text: string): string {
  return text.normalize("NFD").replace(/\p{M}/gu, "").replaceAll("ı", "i");
}

/**
 * The options of a nationality picker, sorted in the reader's own alphabet and
 * findable by the English name, the code and the plain-letter spelling of both
 * names as well, since a desk typing "turkey" or "TR" at a Turkish screen
 * means the same country.
 */
export function countryOptions(locale: string): ComboboxOption[] {
  // One of each for all 250: building either per country is what made the
  // picker's first render the slowest thing in the booking dialog.
  const names = new Intl.DisplayNames([locale], {
    type: "region",
    fallback: "code",
  });
  const english = new Intl.DisplayNames(["en"], {
    type: "region",
    fallback: "code",
  });
  const alphabet = new Intl.Collator(locale);
  return COUNTRY_CODES.map((code) => {
    const label = names.of(code) ?? code;
    const englishNames = [
      english.of(code) ?? code,
      ...(ALSO_KNOWN_AS[code] ?? []),
    ];
    return {
      value: code,
      label,
      keywords: [
        code,
        ...englishNames,
        plain(label),
        ...englishNames.map(plain),
      ],
    };
  }).sort((a, b) => alphabet.compare(a.label, b.label));
}
